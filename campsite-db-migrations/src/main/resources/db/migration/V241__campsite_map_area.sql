-- Map of the console (tab 2): outlines of campsites, sections and pitches as GeoJSON geometries (WGS 84, longitude
-- before latitude). A section may be the area of a power section; a pitch carries its pitch number (the PITCH_NO of
-- the sockets supplying it). Pedestals are placed by the coordinates of their LOCATION.

CREATE SEQUENCE CAMPSITE_MAP_AREA_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE CAMPSITE_MAP_AREA
(
    ID               BIGINT       NOT NULL DEFAULT nextval('CAMPSITE_MAP_AREA_ID_SEQ'),
    SITE_GROUP_ID    BIGINT       NOT NULL,
    AREA_TYPE        VARCHAR(16)  NOT NULL,
    NAME             VARCHAR(128) NOT NULL,
    PITCH_NO         VARCHAR(16),
    POWER_SECTION_ID BIGINT,
    GEOJSON          TEXT         NOT NULL,
    CONSTRAINT PK_CAMPSITE_MAP_AREA PRIMARY KEY (ID),
    CONSTRAINT FK_CAMPSITE_MAP_AREA_SITE_GROUP FOREIGN KEY (SITE_GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT FK_CAMPSITE_MAP_AREA_POWER_SECTION FOREIGN KEY (POWER_SECTION_ID) REFERENCES POWER_SECTION (ID),
    CONSTRAINT UNIQUE_CAMPSITE_MAP_AREA_NAME UNIQUE (SITE_GROUP_ID, AREA_TYPE, NAME),
    CONSTRAINT CHECK_CAMPSITE_MAP_AREA_TYPE CHECK (AREA_TYPE IN ('CAMPSITE', 'SECTION', 'PITCH')),
    CONSTRAINT CHECK_CAMPSITE_MAP_AREA_PITCH CHECK ((AREA_TYPE = 'PITCH') = (PITCH_NO IS NOT NULL)),
    CONSTRAINT CHECK_CAMPSITE_MAP_AREA_GEOJSON CHECK (GEOJSON LIKE '{%}')
);

CREATE INDEX IDX_CAMPSITE_MAP_AREA_SITE_GROUP ON CAMPSITE_MAP_AREA (SITE_GROUP_ID, AREA_TYPE);
