-- Billing account: the account in the ERP the consumption of a guest's cards is billed to. A guest may have several
-- (the reception bill of a stay, the seasonal contract). ERP_ACCOUNT_NO is the number the cards carry
-- (CAMPING_CARD.BILLING_ACCOUNT_NO); an account opened by an order waits for the ERP to assign it.

CREATE SEQUENCE BILLING_ACCOUNT_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE BILLING_ACCOUNT
(
    ID             BIGINT       NOT NULL DEFAULT nextval('BILLING_ACCOUNT_ID_SEQ'),
    GUEST_ID       BIGINT       NOT NULL,
    ERP_ACCOUNT_NO VARCHAR(40),
    DESCRIPTION    VARCHAR(255),
    CREATE_DATE    TIMESTAMP    NOT NULL,
    CLOSED         BOOLEAN      NOT NULL DEFAULT FALSE,
    CLOSE_DATE     TIMESTAMP,
    CONSTRAINT PK_BILLING_ACCOUNT PRIMARY KEY (ID),
    CONSTRAINT FK_BILLING_ACCOUNT_GUEST FOREIGN KEY (GUEST_ID) REFERENCES GUEST (ID),
    CONSTRAINT CHECK_BILLING_ACCOUNT_CLOSED CHECK (CLOSED = FALSE OR CLOSE_DATE IS NOT NULL)
);

CREATE UNIQUE INDEX UNIQUE_BILLING_ACCOUNT_ERP_NO ON BILLING_ACCOUNT (ERP_ACCOUNT_NO) WHERE ERP_ACCOUNT_NO IS NOT NULL;
CREATE INDEX IDX_BILLING_ACCOUNT_GUEST ON BILLING_ACCOUNT (GUEST_ID);
