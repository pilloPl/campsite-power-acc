-- Communication log of the pedestals: boots and consumption records, written for pedestals whose SITE subtree
-- has the communication log switched on (GRP_ATTR_COMMLOG). Gives the last boot / last record in the supplier stock.

CREATE SEQUENCE PEDESTAL_COMM_LOG_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE PEDESTAL_COMM_LOG
(
    ID          BIGINT        NOT NULL DEFAULT nextval('PEDESTAL_COMM_LOG_ID_SEQ'),
    PEDESTAL_ID BIGINT        NOT NULL,
    LOG_DATE    TIMESTAMP     NOT NULL,
    LOG_TYPE    VARCHAR(32)   NOT NULL,
    MESSAGE     VARCHAR(4000),
    CONSTRAINT PK_PEDESTAL_COMM_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_PEDESTAL_COMM_LOG_PEDESTAL FOREIGN KEY (PEDESTAL_ID) REFERENCES PEDESTAL (ID),
    CONSTRAINT CHECK_PEDESTAL_COMM_LOG_TYPE CHECK (LOG_TYPE IN ('BOOT', 'CONSUMPTION_RECORD'))
);

CREATE INDEX IDX_PEDESTAL_COMM_LOG_PEDESTAL ON PEDESTAL_COMM_LOG (PEDESTAL_ID, LOG_TYPE, LOG_DATE);
