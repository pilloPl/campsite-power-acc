-- Supply session: a socket supplies electricity for a camping card or a house card between the pedestal's
-- supplyStarted and supplyStopped. The pedestal repeats unanswered messages, so a session is found again by
-- (socket, card, start meter, remote date). TRANSACTION_ID is the number the pedestal quotes in its stop message;
-- it comes from a sequence. A session without a stop stays ACTIVE until a job closes it on check-out of the stay
-- or after a timeout (STOP_REASON CHECKOUT / TIMEOUT).

CREATE SEQUENCE SUPPLY_SESSION_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE SEQUENCE SUPPLY_TRANSACTION_ID_SEQ START WITH 1000 INCREMENT BY 1 MAXVALUE 2147483647;

CREATE TABLE SUPPLY_SESSION
(
    ID              BIGINT        NOT NULL DEFAULT nextval('SUPPLY_SESSION_ID_SEQ'),
    SOCKET_ID       BIGINT        NOT NULL,
    CARD_ID         BIGINT,
    HOUSECARD_ID    BIGINT,
    TRANSACTION_ID  INTEGER       NOT NULL,
    START_METER_KWH NUMERIC(19, 4),
    REMOTE_DATE     TIMESTAMP,
    CREATE_DATE     TIMESTAMP     NOT NULL,
    ACTIVE          BOOLEAN       NOT NULL DEFAULT TRUE,
    MAX_CURRENT_A   INTEGER       NOT NULL,
    STOP_REASON     VARCHAR(32),
    STOP_DATE       TIMESTAMP,
    STAY_ID         BIGINT,
    UNIT_PLATE      VARCHAR(32),
    CONSTRAINT PK_SUPPLY_SESSION PRIMARY KEY (ID),
    CONSTRAINT FK_SUPPLY_SESSION_SOCKET FOREIGN KEY (SOCKET_ID) REFERENCES SOCKET (ID),
    CONSTRAINT FK_SUPPLY_SESSION_CARD FOREIGN KEY (CARD_ID) REFERENCES CAMPING_CARD (ID),
    CONSTRAINT FK_SUPPLY_SESSION_HOUSECARD FOREIGN KEY (HOUSECARD_ID) REFERENCES HOUSECARD (ID),
    CONSTRAINT UNIQUE_SUPPLY_SESSION_TRANSACTION UNIQUE (TRANSACTION_ID),
    CONSTRAINT CHECK_SUPPLY_SESSION_ONE_CARD CHECK (CARD_ID IS NULL OR HOUSECARD_ID IS NULL),
    CONSTRAINT CHECK_SUPPLY_SESSION_MAX_CURRENT CHECK (MAX_CURRENT_A > 0),
    CONSTRAINT CHECK_SUPPLY_SESSION_STOP_REASON CHECK (STOP_REASON IN ('LOCAL', 'REMOTE', 'UNPLUGGED',
        'BREAKER_TRIP', 'POWER_LOSS', 'REBOOT', 'EMERGENCY_STOP', 'CHECKOUT', 'TIMEOUT', 'OTHER'))
);

CREATE INDEX IDX_SUPPLY_SESSION_SOCKET ON SUPPLY_SESSION (SOCKET_ID, ACTIVE);
CREATE INDEX IDX_SUPPLY_SESSION_CARD ON SUPPLY_SESSION (CARD_ID);
CREATE INDEX IDX_SUPPLY_SESSION_HOUSECARD ON SUPPLY_SESSION (HOUSECARD_ID);
CREATE INDEX IDX_SUPPLY_SESSION_ACTIVE_CREATED ON SUPPLY_SESSION (CREATE_DATE) WHERE ACTIVE;
CREATE INDEX IDX_SUPPLY_SESSION_ACTIVE_STAY ON SUPPLY_SESSION (STAY_ID) WHERE ACTIVE;
