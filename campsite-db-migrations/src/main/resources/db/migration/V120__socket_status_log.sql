-- Monitoring log of the sockets: one row per status period of a monitored socket (status, error flags or current
-- changed), moved forward (UPDATE_DATE, METER_KWH) while nothing changes. Written by SocketStateTaskWorker only for
-- sockets with MONITORING switched on. Source of the status report and of the utilization view.

CREATE SEQUENCE SOCKET_STATUS_LOG_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE SOCKET_STATUS_LOG
(
    ID          BIGINT         NOT NULL DEFAULT nextval('SOCKET_STATUS_LOG_ID_SEQ'),
    SOCKET_ID   BIGINT         NOT NULL,
    CREATE_DATE TIMESTAMP      NOT NULL,
    UPDATE_DATE TIMESTAMP      NOT NULL,
    REMOTE_DATE TIMESTAMP,
    STATUS      VARCHAR(32)    NOT NULL,
    METER_KWH   NUMERIC(19, 4) NOT NULL DEFAULT 0,
    ERROR_FLAGS BIGINT         NOT NULL DEFAULT 0,
    CURRENT_A   NUMERIC(7, 2),
    CONSTRAINT PK_SOCKET_STATUS_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_SOCKET_STATUS_LOG_SOCKET FOREIGN KEY (SOCKET_ID) REFERENCES SOCKET (ID),
    CONSTRAINT CHECK_SOCKET_STATUS_LOG_STATUS CHECK (STATUS IN ('AVAILABLE', 'OCCUPIED', 'SUPPLYING',
        'SUPPLYING_WITHOUT_CONSUMPTION', 'BREAKER_TRIPPED', 'FAULTED', 'UNAVAILABLE', 'FIRMWARE_UPDATE', 'UNKNOWN'))
);

CREATE INDEX IDX_SOCKET_STATUS_LOG_SOCKET ON SOCKET_STATUS_LOG (SOCKET_ID, CREATE_DATE);
CREATE INDEX IDX_SOCKET_STATUS_LOG_CREATED ON SOCKET_STATUS_LOG (CREATE_DATE);
