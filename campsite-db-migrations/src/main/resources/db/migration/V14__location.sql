-- Address of a campsite (pedestals stand on it) and the opening hours of its reception.
-- A pedestal back in the supplier stock points to the UNKNOWN location (seed id 1).

CREATE SEQUENCE LOCATION_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE LOCATION
(
    ID           BIGINT         NOT NULL DEFAULT nextval('LOCATION_ID_SEQ'),
    NAME         VARCHAR(256),
    STREET       VARCHAR(128)   NOT NULL,
    HOUSE_NUMBER VARCHAR(16)    NOT NULL,
    ZIPCODE      VARCHAR(12)    NOT NULL,
    CITY         VARCHAR(128)   NOT NULL,
    REGION       VARCHAR(128),
    COUNTRY_ISO  VARCHAR(3),
    LATITUDE     NUMERIC(14, 10),
    LONGITUDE    NUMERIC(14, 10),
    NOTE         VARCHAR(256),
    DELETED      BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_LOCATION PRIMARY KEY (ID)
);

CREATE SEQUENCE RECEPTION_HOURS_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE RECEPTION_HOURS
(
    ID          BIGINT      NOT NULL DEFAULT nextval('RECEPTION_HOURS_ID_SEQ'),
    LOCATION_ID BIGINT      NOT NULL,
    DAY_OF_WEEK VARCHAR(16) NOT NULL,
    OPEN_FROM   TIME        NOT NULL,
    OPEN_TO     TIME        NOT NULL,
    CONSTRAINT PK_RECEPTION_HOURS PRIMARY KEY (ID),
    CONSTRAINT FK_RECEPTION_HOURS_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES LOCATION (ID),
    CONSTRAINT CHECK_RECEPTION_HOURS_DAY CHECK (DAY_OF_WEEK IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

CREATE INDEX IDX_RECEPTION_HOURS_LOCATION ON RECEPTION_HOURS (LOCATION_ID);

