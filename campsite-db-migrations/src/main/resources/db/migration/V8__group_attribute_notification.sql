-- Service mail recipients per notification type, inherited by the SITE subtree (nearest wins).

CREATE TABLE GRP_ATTR_NOTIFICATION
(
    ID                BIGINT       NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID          BIGINT       NOT NULL,
    NAME              VARCHAR(256) NOT NULL,
    EMAIL             VARCHAR(256) NOT NULL,
    NOTIFICATION_TYPE VARCHAR(64)  NOT NULL,
    CONSTRAINT PK_GRP_ATTR_NOTIFICATION PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_NOTIFICATION_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_NOTIFICATION UNIQUE (GROUP_ID, NOTIFICATION_TYPE)
);
