-- Organisation: three typed trees in one table (ISSUER, SITE, STAFF).
-- Names carry logic (market prefix "HR ", affiliate prefix "AFFILIATE ", roots looked up by name),
-- therefore a name is unique within its type.

CREATE SEQUENCE GROUP_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE TBL_GROUP
(
    ID          BIGINT       NOT NULL DEFAULT nextval('GROUP_ID_SEQ'),
    PARENT_ID   BIGINT,
    NAME        VARCHAR(255) NOT NULL,
    TYPENAME    VARCHAR(255) NOT NULL,
    DISPLAYNAME VARCHAR(256) NOT NULL,
    CONSTRAINT PK_GROUP PRIMARY KEY (ID),
    CONSTRAINT FK_GROUP_PARENT FOREIGN KEY (PARENT_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GROUP_NAME_TYPENAME UNIQUE (NAME, TYPENAME),
    CONSTRAINT CHECK_GROUP_TYPENAME CHECK (TYPENAME IN ('ISSUER', 'SITE', 'STAFF'))
);

CREATE INDEX IDX_GROUP_PARENT ON TBL_GROUP (PARENT_ID);
