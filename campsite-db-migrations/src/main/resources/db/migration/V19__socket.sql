-- Socket on a pedestal: CEE / Schuko socket with its own kWh meter and breaker, optionally assigned to a pitch.
-- SOCKET_CODE (campsite code + pedestal + socket number) is given at commissioning and cleared when the pedestal
-- goes back to the supplier.

CREATE SEQUENCE SOCKET_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE SOCKET
(
    ID                 BIGINT         NOT NULL DEFAULT nextval('SOCKET_ID_SEQ'),
    PEDESTAL_ID        BIGINT         NOT NULL,
    SOCKET_TYPE_ID     BIGINT         NOT NULL,
    NAME               VARCHAR(128)   NOT NULL,
    POS                INTEGER        NOT NULL,
    SOCKET_NO          INTEGER,
    SOCKET_CODE        VARCHAR(64),
    PITCH_NO           VARCHAR(16),
    METER_KWH          NUMERIC(19, 4) NOT NULL DEFAULT 0,
    STATUS             VARCHAR(32)    NOT NULL DEFAULT 'UNKNOWN',
    MOD_DATE           TIMESTAMP      NOT NULL,
    LAST_STATUS_UPDATE TIMESTAMP,
    FIRMWARE_VERSION   VARCHAR(64),
    MONITORING         BOOLEAN        NOT NULL DEFAULT FALSE,
    FREE_SOCKET        BOOLEAN        NOT NULL DEFAULT FALSE,
    DELETED            BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_SOCKET PRIMARY KEY (ID),
    CONSTRAINT FK_SOCKET_PEDESTAL FOREIGN KEY (PEDESTAL_ID) REFERENCES PEDESTAL (ID),
    CONSTRAINT FK_SOCKET_TYPE FOREIGN KEY (SOCKET_TYPE_ID) REFERENCES SOCKET_TYPE (ID),
    CONSTRAINT UNIQUE_SOCKET_CODE UNIQUE (SOCKET_CODE),
    CONSTRAINT CHECK_SOCKET_STATUS CHECK (STATUS IN ('AVAILABLE', 'OCCUPIED', 'SUPPLYING', 'SUPPLYING_WITHOUT_CONSUMPTION',
        'BREAKER_TRIPPED', 'FAULTED', 'UNAVAILABLE', 'FIRMWARE_UPDATE', 'UNKNOWN'))
);

CREATE INDEX IDX_SOCKET_PEDESTAL ON SOCKET (PEDESTAL_ID);
CREATE INDEX IDX_SOCKET_PITCH ON SOCKET (PITCH_NO);
