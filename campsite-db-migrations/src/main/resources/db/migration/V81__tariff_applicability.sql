-- Tariff assigned to a socket or to a whole pedestal from a start date on. Rows are kept as history: the active
-- assignment at a time is the one with the newest START_DATE not after that time (socket before pedestal).

CREATE SEQUENCE TARIFF_APPLICABILITY_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE TARIFF_APPLICABILITY
(
    ID          BIGINT    NOT NULL DEFAULT nextval('TARIFF_APPLICABILITY_ID_SEQ'),
    TARIFF_ID   BIGINT    NOT NULL,
    SOCKET_ID   BIGINT,
    PEDESTAL_ID BIGINT,
    START_DATE  TIMESTAMP NOT NULL,
    CREATED_BY  VARCHAR(255),
    CREATE_DATE TIMESTAMP NOT NULL,
    CONSTRAINT PK_TARIFF_APPLICABILITY PRIMARY KEY (ID),
    CONSTRAINT FK_TARIFF_APPLICABILITY_TARIFF FOREIGN KEY (TARIFF_ID) REFERENCES TARIFF (ID),
    CONSTRAINT FK_TARIFF_APPLICABILITY_SOCKET FOREIGN KEY (SOCKET_ID) REFERENCES SOCKET (ID),
    CONSTRAINT FK_TARIFF_APPLICABILITY_PEDESTAL FOREIGN KEY (PEDESTAL_ID) REFERENCES PEDESTAL (ID),
    CONSTRAINT CHECK_TARIFF_APPLICABILITY_TARGET CHECK ((SOCKET_ID IS NULL) <> (PEDESTAL_ID IS NULL))
);

CREATE INDEX IDX_TARIFF_APPLICABILITY_SOCKET ON TARIFF_APPLICABILITY (SOCKET_ID, START_DATE);
CREATE INDEX IDX_TARIFF_APPLICABILITY_PEDESTAL ON TARIFF_APPLICABILITY (PEDESTAL_ID, START_DATE);
