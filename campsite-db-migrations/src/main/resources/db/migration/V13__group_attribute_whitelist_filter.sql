-- Card exchange filter of an ISSUER subtree; per direction the nearest filter covering it wins.

CREATE TABLE GRP_ATTR_WHITELIST_FILTER
(
    ID                    BIGINT      NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID              BIGINT      NOT NULL,
    SYNCHRONIZABLE        BOOLEAN     NOT NULL,
    WHITELIST_FILTER_TYPE VARCHAR(32) NOT NULL,
    CONSTRAINT PK_GRP_ATTR_WHITELIST_FILTER PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_WHITELIST_FILTER_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_WHITELIST_FILTER UNIQUE (GROUP_ID)
);
