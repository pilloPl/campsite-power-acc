-- Issuer sync status: the last run of each direction of the exchange with a partner. LAST_SUCCESS is the watermark
-- of the record export (records with plug-out after the last successful export) and what the console shows.

CREATE SEQUENCE ISSUER_SYNC_STATUS_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE ISSUER_SYNC_STATUS
(
    ID                BIGINT        NOT NULL DEFAULT nextval('ISSUER_SYNC_STATUS_ID_SEQ'),
    ISSUER_PARTNER_ID BIGINT        NOT NULL,
    DIRECTION         VARCHAR(16)   NOT NULL,
    STATUS            VARCHAR(8)    NOT NULL,
    LAST_RUN          TIMESTAMP     NOT NULL,
    LAST_SUCCESS      TIMESTAMP,
    ITEMS_ACCEPTED    INTEGER       NOT NULL DEFAULT 0,
    ITEMS_REJECTED    INTEGER       NOT NULL DEFAULT 0,
    MESSAGE           VARCHAR(1000),
    CONSTRAINT PK_ISSUER_SYNC_STATUS PRIMARY KEY (ID),
    CONSTRAINT FK_ISSUER_SYNC_STATUS_PARTNER FOREIGN KEY (ISSUER_PARTNER_ID) REFERENCES ISSUER_PARTNER (ID),
    CONSTRAINT UNIQUE_ISSUER_SYNC_STATUS UNIQUE (ISSUER_PARTNER_ID, DIRECTION),
    CONSTRAINT CHECK_ISSUER_SYNC_STATUS_DIRECTION CHECK (DIRECTION IN ('CARD_IMPORT', 'CARD_EXPORT', 'RECORD_EXPORT',
        'RECORD_IMPORT')),
    CONSTRAINT CHECK_ISSUER_SYNC_STATUS_STATUS CHECK (STATUS IN ('OK', 'ERROR')),
    CONSTRAINT CHECK_ISSUER_SYNC_STATUS_ITEMS CHECK (ITEMS_ACCEPTED >= 0 AND ITEMS_REJECTED >= 0)
);
