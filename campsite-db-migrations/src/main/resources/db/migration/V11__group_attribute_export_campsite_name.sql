-- Campsite name used in exports, inherited by the SITE subtree (nearest wins).

CREATE TABLE GRP_ATTR_EXPORT_CAMPSITE_NAME
(
    ID       BIGINT       NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID BIGINT       NOT NULL,
    NAME     VARCHAR(256) NOT NULL,
    CONSTRAINT PK_GRP_ATTR_EXPORT_CAMPSITE_NAME PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_EXPORT_CAMPSITE_NAME_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_EXPORT_CAMPSITE_NAME UNIQUE (GROUP_ID)
);
