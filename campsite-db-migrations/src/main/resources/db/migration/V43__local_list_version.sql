-- Version of the local card list last sent to a pedestal controller; the controller rejects lists with an older
-- version. One row per pedestal.

CREATE SEQUENCE LOCAL_LIST_VERSION_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE LOCAL_LIST_VERSION
(
    ID          BIGINT    NOT NULL DEFAULT nextval('LOCAL_LIST_VERSION_ID_SEQ'),
    PEDESTAL_ID BIGINT    NOT NULL,
    VERSION     INTEGER   NOT NULL,
    MOD_DATE    TIMESTAMP NOT NULL,
    CONSTRAINT PK_LOCAL_LIST_VERSION PRIMARY KEY (ID),
    CONSTRAINT FK_LOCAL_LIST_VERSION_PEDESTAL FOREIGN KEY (PEDESTAL_ID) REFERENCES PEDESTAL (ID),
    CONSTRAINT UNIQUE_LOCAL_LIST_VERSION_PEDESTAL UNIQUE (PEDESTAL_ID)
);
