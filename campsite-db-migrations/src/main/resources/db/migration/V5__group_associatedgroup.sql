-- Acceptance agreement: cards of the ISSUER group GROUP_ID are accepted in the SITE subtree ASSOCIATEDGROUP_ID.
-- Semantics (one for Java and SQL): the nearest ancestor-or-self with a non-empty agreement list replaces
-- the lists of all groups above it.
CREATE TABLE GROUP_ASSOCIATEDGROUP
(
    GROUP_ID           BIGINT NOT NULL,
    ASSOCIATEDGROUP_ID BIGINT NOT NULL,
    CONSTRAINT PK_GROUP_ASSOCIATEDGROUP PRIMARY KEY (GROUP_ID, ASSOCIATEDGROUP_ID),
    CONSTRAINT FK_GROUP_ASSOCIATEDGROUP_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT FK_GROUP_ASSOCIATEDGROUP_ASSOC FOREIGN KEY (ASSOCIATEDGROUP_ID) REFERENCES TBL_GROUP (ID)
);

CREATE INDEX IDX_GROUP_ASSOCIATEDGROUP_ASSOC ON GROUP_ASSOCIATEDGROUP (ASSOCIATEDGROUP_ID);
