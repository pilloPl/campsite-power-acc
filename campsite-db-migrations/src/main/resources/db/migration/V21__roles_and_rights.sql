-- RBAC: a security group bundles roles, a role bundles rights. Users get roles directly or through security groups.
-- SELF_SERVICE marks the roles of the self-service console (affiliate owners, seasonal residents).

CREATE SEQUENCE USERROLE_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE USERRIGHT
(
    ID   BIGINT       NOT NULL DEFAULT nextval('USERROLE_ID_SEQ'),
    NAME VARCHAR(255) NOT NULL,
    CONSTRAINT PK_USERRIGHT PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_USERRIGHT_NAME UNIQUE (NAME)
);

CREATE TABLE USERROLE
(
    ID           BIGINT       NOT NULL DEFAULT nextval('USERROLE_ID_SEQ'),
    NAME         VARCHAR(255) NOT NULL,
    GROUP_TYPES  VARCHAR(255),
    SORT_KEY     BIGINT       NOT NULL,
    SELF_SERVICE BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_USERROLE PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_USERROLE_NAME UNIQUE (NAME)
);

CREATE TABLE USERROLE_USERRIGHT
(
    ROLE_ID  BIGINT NOT NULL,
    RIGHT_ID BIGINT NOT NULL,
    CONSTRAINT PK_USERROLE_USERRIGHT PRIMARY KEY (ROLE_ID, RIGHT_ID),
    CONSTRAINT FK_USERROLE_USERRIGHT_ROLE FOREIGN KEY (ROLE_ID) REFERENCES USERROLE (ID),
    CONSTRAINT FK_USERROLE_USERRIGHT_RIGHT FOREIGN KEY (RIGHT_ID) REFERENCES USERRIGHT (ID)
);

CREATE TABLE SECURITYGROUP
(
    ID   BIGINT       NOT NULL DEFAULT nextval('USERROLE_ID_SEQ'),
    NAME VARCHAR(255) NOT NULL,
    CONSTRAINT PK_SECURITYGROUP PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_SECURITYGROUP_NAME UNIQUE (NAME)
);

CREATE TABLE SECURITYGROUP_USERROLE
(
    SECURITYGROUP_ID BIGINT NOT NULL,
    USERROLE_ID      BIGINT NOT NULL,
    CONSTRAINT PK_SECURITYGROUP_USERROLE PRIMARY KEY (SECURITYGROUP_ID, USERROLE_ID),
    CONSTRAINT FK_SECURITYGROUP_USERROLE_SG FOREIGN KEY (SECURITYGROUP_ID) REFERENCES SECURITYGROUP (ID),
    CONSTRAINT FK_SECURITYGROUP_USERROLE_ROLE FOREIGN KEY (USERROLE_ID) REFERENCES USERROLE (ID)
);

