-- Socket types: the plug standard and the default breaker rating of the socket.

CREATE SEQUENCE SOCKET_TYPE_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE SOCKET_TYPE
(
    ID                BIGINT       NOT NULL DEFAULT nextval('SOCKET_TYPE_ID_SEQ'),
    NAME              VARCHAR(128) NOT NULL,
    PLUG_STANDARD     VARCHAR(32)  NOT NULL,
    PHASES            INTEGER      NOT NULL,
    BREAKER_RATING_ID BIGINT       NOT NULL,
    DELETED           BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_SOCKET_TYPE PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_SOCKET_TYPE_NAME UNIQUE (NAME),
    CONSTRAINT FK_SOCKET_TYPE_BREAKER_RATING FOREIGN KEY (BREAKER_RATING_ID) REFERENCES BREAKER_RATING (ID),
    CONSTRAINT CHECK_SOCKET_TYPE_PLUG CHECK (PLUG_STANDARD IN ('CEE_BLUE_16A', 'CEE_RED_32A', 'SCHUKO')),
    CONSTRAINT CHECK_SOCKET_TYPE_PHASES CHECK (PHASES IN (1, 3))
);

