-- Ratings of the breaker protecting a socket (6 / 10 / 16 / 32 A), one row per BreakerRating.

CREATE TABLE BREAKER_RATING
(
    ID                BIGINT        NOT NULL,
    RATING            VARCHAR(8)    NOT NULL,
    NOMINAL_CURRENT_A NUMERIC(6, 2) NOT NULL,
    NOMINAL_VOLTAGE_V NUMERIC(6, 2) NOT NULL,
    MAXIMUM_POWER_KW  NUMERIC(8, 3) NOT NULL,
    CONSTRAINT PK_BREAKER_RATING PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_BREAKER_RATING UNIQUE (RATING),
    CONSTRAINT CHECK_BREAKER_RATING CHECK (RATING IN ('A6', 'A10', 'A16', 'A32'))
);

INSERT INTO BREAKER_RATING (ID, RATING, NOMINAL_CURRENT_A, NOMINAL_VOLTAGE_V, MAXIMUM_POWER_KW) VALUES
    (1, 'A6', 6, 230, 1.380),
    (2, 'A10', 10, 230, 2.300),
    (3, 'A16', 16, 230, 3.680),
    (4, 'A32', 32, 230, 7.360);
