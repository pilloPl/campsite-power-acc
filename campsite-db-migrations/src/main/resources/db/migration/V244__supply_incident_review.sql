-- Supply incidents (stops the pedestal backend could not book) are reviewed by the service team in the console
-- (tab Supply sessions): who looked at the incident, when, and what was found.

ALTER TABLE SUPPLY_INCIDENT_LOG ADD COLUMN REVIEWED_BY VARCHAR(100);
ALTER TABLE SUPPLY_INCIDENT_LOG ADD COLUMN REVIEW_DATE TIMESTAMP;
ALTER TABLE SUPPLY_INCIDENT_LOG ADD COLUMN REVIEW_COMMENT VARCHAR(1000);
ALTER TABLE SUPPLY_INCIDENT_LOG ADD CONSTRAINT CHECK_SUPPLY_INCIDENT_LOG_REVIEW
    CHECK ((REVIEWED_BY IS NULL) = (REVIEW_DATE IS NULL));

CREATE INDEX IDX_SUPPLY_INCIDENT_LOG_UNREVIEWED ON SUPPLY_INCIDENT_LOG (CREATE_DATE) WHERE REVIEWED_BY IS NULL;
