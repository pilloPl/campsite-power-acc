-- The one price model: a tariff of a market consists of elements, an element of price components (ENERGY per kWh,
-- TIME per hour, PER_NIGHT per night of the stay, FLAT per session) and an optional restriction (hours, season
-- dates, days of the week, kWh range of the session). At most one default tariff per market.

CREATE SEQUENCE TARIFF_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE TARIFF
(
    ID             BIGINT       NOT NULL DEFAULT nextval('TARIFF_ID_SEQ'),
    NAME           VARCHAR(128) NOT NULL,
    DESCRIPTION    VARCHAR(512) NOT NULL,
    MARKET         VARCHAR(8)   NOT NULL,
    CURRENCY       VARCHAR(3)   NOT NULL DEFAULT 'EUR',
    DEFAULT_TARIFF BOOLEAN      NOT NULL DEFAULT FALSE,
    LUD            TIMESTAMP    NOT NULL,
    CONSTRAINT PK_TARIFF PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_TARIFF_NAME_MARKET UNIQUE (NAME, MARKET),
    CONSTRAINT CHECK_TARIFF_MARKET CHECK (MARKET IN ('HR', 'IT', 'FR'))
);

CREATE UNIQUE INDEX UNIQUE_TARIFF_DEFAULT_PER_MARKET ON TARIFF (MARKET) WHERE DEFAULT_TARIFF;

CREATE SEQUENCE TARIFF_ELEMENT_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE TARIFF_ELEMENT
(
    ID        BIGINT  NOT NULL DEFAULT nextval('TARIFF_ELEMENT_ID_SEQ'),
    TARIFF_ID BIGINT  NOT NULL,
    POS       INTEGER NOT NULL,
    CONSTRAINT PK_TARIFF_ELEMENT PRIMARY KEY (ID),
    CONSTRAINT FK_TARIFF_ELEMENT_TARIFF FOREIGN KEY (TARIFF_ID) REFERENCES TARIFF (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_TARIFF_ELEMENT_TARIFF ON TARIFF_ELEMENT (TARIFF_ID);

CREATE SEQUENCE PRICE_COMPONENT_ID_SEQ START WITH 1000 INCREMENT BY 1;

-- STEP_SIZE: Wh for ENERGY, seconds for TIME, nights for PER_NIGHT, 1 for FLAT. Units are rounded up to it.
CREATE TABLE PRICE_COMPONENT
(
    ID                BIGINT         NOT NULL DEFAULT nextval('PRICE_COMPONENT_ID_SEQ'),
    TARIFF_ELEMENT_ID BIGINT         NOT NULL,
    DIMENSION_TYPE    VARCHAR(16)    NOT NULL,
    PRICE             NUMERIC(12, 4) NOT NULL,
    STEP_SIZE         INTEGER        NOT NULL DEFAULT 1,
    CONSTRAINT PK_PRICE_COMPONENT PRIMARY KEY (ID),
    CONSTRAINT FK_PRICE_COMPONENT_ELEMENT FOREIGN KEY (TARIFF_ELEMENT_ID) REFERENCES TARIFF_ELEMENT (ID)
        ON DELETE CASCADE,
    CONSTRAINT CHECK_PRICE_COMPONENT_DIMENSION CHECK (DIMENSION_TYPE IN ('ENERGY', 'TIME', 'FLAT', 'PER_NIGHT')),
    CONSTRAINT CHECK_PRICE_COMPONENT_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CHECK_PRICE_COMPONENT_STEP_SIZE CHECK (STEP_SIZE > 0)
);

CREATE INDEX IDX_PRICE_COMPONENT_ELEMENT ON PRICE_COMPONENT (TARIFF_ELEMENT_ID);

CREATE SEQUENCE TARIFF_RESTRICTION_ID_SEQ START WITH 1000 INCREMENT BY 1;

-- END_TIME before START_TIME wraps over midnight (night 22:00-06:00). END_DATE is the last day of the season.
CREATE TABLE TARIFF_RESTRICTION
(
    ID                BIGINT NOT NULL DEFAULT nextval('TARIFF_RESTRICTION_ID_SEQ'),
    TARIFF_ELEMENT_ID BIGINT NOT NULL,
    START_TIME        TIME,
    END_TIME          TIME,
    START_DATE        DATE,
    END_DATE          DATE,
    MIN_KWH           NUMERIC(19, 4),
    MAX_KWH           NUMERIC(19, 4),
    CONSTRAINT PK_TARIFF_RESTRICTION PRIMARY KEY (ID),
    CONSTRAINT FK_TARIFF_RESTRICTION_ELEMENT FOREIGN KEY (TARIFF_ELEMENT_ID) REFERENCES TARIFF_ELEMENT (ID)
        ON DELETE CASCADE,
    CONSTRAINT UNIQUE_TARIFF_RESTRICTION_ELEMENT UNIQUE (TARIFF_ELEMENT_ID),
    CONSTRAINT CHECK_TARIFF_RESTRICTION_TIMES CHECK ((START_TIME IS NULL) = (END_TIME IS NULL)),
    CONSTRAINT CHECK_TARIFF_RESTRICTION_DATES CHECK (START_DATE IS NULL OR END_DATE IS NULL OR START_DATE <= END_DATE),
    CONSTRAINT CHECK_TARIFF_RESTRICTION_KWH CHECK (MIN_KWH IS NULL OR MAX_KWH IS NULL OR MIN_KWH < MAX_KWH)
);

CREATE TABLE TARIFF_RESTRICTION_DAY
(
    RESTRICTION_ID BIGINT      NOT NULL,
    DAY_OF_WEEK    VARCHAR(16) NOT NULL,
    CONSTRAINT PK_TARIFF_RESTRICTION_DAY PRIMARY KEY (RESTRICTION_ID, DAY_OF_WEEK),
    CONSTRAINT FK_TARIFF_RESTRICTION_DAY_RESTRICTION FOREIGN KEY (RESTRICTION_ID) REFERENCES TARIFF_RESTRICTION (ID)
        ON DELETE CASCADE,
    CONSTRAINT CHECK_TARIFF_RESTRICTION_DAY CHECK (DAY_OF_WEEK IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY',
        'FRIDAY', 'SATURDAY', 'SUNDAY'))
);
