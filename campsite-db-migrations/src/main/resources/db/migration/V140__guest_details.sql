-- Guest details kept flat on the guest, as the reception enters them: postal address, contact channels, bank
-- account for the seasonal direct debit, organisation for club or company guests, and the plates of the car and
-- the trailer the barrier camera reads. ERP_PARTNER_NO is set once the ERP has created the partner.

ALTER TABLE GUEST
    ADD COLUMN SALUTATION         VARCHAR(16),
    ADD COLUMN INITIALS           VARCHAR(32),
    ADD COLUMN STREET             VARCHAR(100),
    ADD COLUMN HOUSE_NO           VARCHAR(16),
    ADD COLUMN HOUSE_NO_ADD       VARCHAR(16),
    ADD COLUMN ZIP_CODE           VARCHAR(16),
    ADD COLUMN CITY               VARCHAR(100),
    ADD COLUMN COUNTRY_ISO        VARCHAR(2),
    ADD COLUMN LANGUAGE           VARCHAR(8),
    ADD COLUMN PHONE              VARCHAR(32),
    ADD COLUMN MOBILE             VARCHAR(32),
    ADD COLUMN EMAIL_NOTIFICATION BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN SMS_NOTIFICATION   BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN BANK_ACCOUNT_NAME  VARCHAR(200),
    ADD COLUMN IBAN               VARCHAR(34),
    ADD COLUMN PAYMENT_METHOD     VARCHAR(32),
    ADD COLUMN ORGANISATION_NAME  VARCHAR(200),
    ADD COLUMN VAT_NUMBER         VARCHAR(32),
    ADD COLUMN REFERENCE_NO       VARCHAR(100),
    ADD COLUMN CAR_PLATE          VARCHAR(32),
    ADD COLUMN TRAILER_PLATE      VARCHAR(32),
    ADD COLUMN REMARKS            VARCHAR(1000),
    ADD COLUMN MOD_DATE           TIMESTAMP;

ALTER TABLE GUEST
    ADD CONSTRAINT CHECK_GUEST_PAYMENT_METHOD CHECK (PAYMENT_METHOD IS NULL
        OR PAYMENT_METHOD IN ('RECEPTION', 'DIRECT_DEBIT', 'INVOICE'));

CREATE INDEX IDX_GUEST_NAME ON GUEST (LOWER(NAME));
CREATE INDEX IDX_GUEST_ERP_PARTNER_NO ON GUEST (ERP_PARTNER_NO);
CREATE INDEX IDX_GUEST_CAR_PLATE ON GUEST (CAR_PLATE);
