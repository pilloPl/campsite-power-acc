-- Console users. GROUP_ID is the user's own place in the STAFF tree (who administers the user);
-- USERINFO_GROUP holds at most one group per tree giving the scope of the user (STAFF / SITE / ISSUER).

CREATE SEQUENCE USERINFO_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE USERINFO
(
    ID                    BIGINT       NOT NULL DEFAULT nextval('USERINFO_ID_SEQ'),
    USERNAME              VARCHAR(128) NOT NULL,
    PASSWORD_HASH         VARCHAR(256),
    NAME                  VARCHAR(256) NOT NULL,
    EMAIL                 VARCHAR(256) NOT NULL,
    STATUS                VARCHAR(16)  NOT NULL,
    EMAIL_LOCALE          VARCHAR(8),
    GROUP_ID              BIGINT,
    SETTLEMENT_PARTNER_NO VARCHAR(255),
    CREATE_DATE           TIMESTAMP    NOT NULL,
    DELETED               BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_USERINFO PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_USERINFO_USERNAME UNIQUE (USERNAME),
    CONSTRAINT FK_USERINFO_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT CHECK_USERINFO_STATUS CHECK (STATUS IN ('INVITED', 'ACTIVE', 'LOCKED', 'DEACTIVATED'))
);

CREATE INDEX IDX_USERINFO_GROUP ON USERINFO (GROUP_ID);
CREATE INDEX IDX_USERINFO_EMAIL ON USERINFO (LOWER(EMAIL));

CREATE TABLE USERINFO_USERROLE
(
    USERINFO_ID BIGINT NOT NULL,
    USERROLE_ID BIGINT NOT NULL,
    CONSTRAINT PK_USERINFO_USERROLE PRIMARY KEY (USERINFO_ID, USERROLE_ID),
    CONSTRAINT FK_USERINFO_USERROLE_USER FOREIGN KEY (USERINFO_ID) REFERENCES USERINFO (ID),
    CONSTRAINT FK_USERINFO_USERROLE_ROLE FOREIGN KEY (USERROLE_ID) REFERENCES USERROLE (ID)
);

CREATE TABLE USERINFO_SECURITYGROUP
(
    USERINFO_ID      BIGINT NOT NULL,
    SECURITYGROUP_ID BIGINT NOT NULL,
    CONSTRAINT PK_USERINFO_SECURITYGROUP PRIMARY KEY (USERINFO_ID, SECURITYGROUP_ID),
    CONSTRAINT FK_USERINFO_SECURITYGROUP_USER FOREIGN KEY (USERINFO_ID) REFERENCES USERINFO (ID),
    CONSTRAINT FK_USERINFO_SECURITYGROUP_SG FOREIGN KEY (SECURITYGROUP_ID) REFERENCES SECURITYGROUP (ID)
);

CREATE TABLE USERINFO_GROUP
(
    USERINFO_ID BIGINT NOT NULL,
    GROUP_ID    BIGINT NOT NULL,
    CONSTRAINT PK_USERINFO_GROUP PRIMARY KEY (USERINFO_ID, GROUP_ID),
    CONSTRAINT FK_USERINFO_GROUP_USER FOREIGN KEY (USERINFO_ID) REFERENCES USERINFO (ID),
    CONSTRAINT FK_USERINFO_GROUP_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID)
);

CREATE INDEX IDX_USERINFO_GROUP_GROUP ON USERINFO_GROUP (GROUP_ID);
