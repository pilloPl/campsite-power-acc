-- Camping card: RFID card issued at the reception for a stay (validity = the stay) or for the season (seasonal
-- resident), or a card of an issuer accepted by agreement. CARD_RFID is the decimal UID as the pedestal readers send
-- it, CARD_NUMBER is printed on the card. The validity days are inclusive.
-- PARTNER_SYNC_STATE / TARGET_PARTNER_SYNC_STATE drive the card list exchange with issuers.

CREATE SEQUENCE CAMPING_CARD_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE CAMPING_CARD
(
    ID                        BIGINT       NOT NULL DEFAULT nextval('CAMPING_CARD_ID_SEQ'),
    CARD_RFID                 VARCHAR(64)  NOT NULL,
    CARD_NUMBER               VARCHAR(64)  NOT NULL,
    STATUS                    VARCHAR(16)  NOT NULL DEFAULT 'ACTIVATED',
    GUEST_ID                  BIGINT,
    VALID_FROM                DATE,
    VALID_TO                  DATE,
    BILLING_ACCOUNT_NO        VARCHAR(40),
    DELETED                   BOOLEAN      NOT NULL DEFAULT FALSE,
    CREATE_DATE               TIMESTAMP    NOT NULL,
    UPLOAD_DATE               TIMESTAMP,
    PARTNER_SYNC_STATE        VARCHAR(16)  NOT NULL DEFAULT 'ADD',
    TARGET_PARTNER_SYNC_STATE VARCHAR(16),
    CONSTRAINT PK_CAMPING_CARD PRIMARY KEY (ID),
    CONSTRAINT FK_CAMPING_CARD_GUEST FOREIGN KEY (GUEST_ID) REFERENCES GUEST (ID),
    CONSTRAINT CHECK_CAMPING_CARD_STATUS CHECK (STATUS IN ('ACTIVATED', 'DEACTIVATED')),
    CONSTRAINT CHECK_CAMPING_CARD_SYNC CHECK (PARTNER_SYNC_STATE IN ('ADD', 'MODIFY', 'DELETE', 'UNKNOWN', 'NOT', 'NEVER')),
    CONSTRAINT CHECK_CAMPING_CARD_TARGET_SYNC CHECK (TARGET_PARTNER_SYNC_STATE IS NULL
        OR TARGET_PARTNER_SYNC_STATE IN ('ADD', 'MODIFY', 'DELETE', 'UNKNOWN', 'NOT', 'NEVER')),
    CONSTRAINT CHECK_CAMPING_CARD_VALIDITY CHECK (VALID_FROM IS NULL OR VALID_TO IS NULL OR VALID_FROM <= VALID_TO)
);

-- one living card per UID and printed number; deleted cards stay for the history
CREATE UNIQUE INDEX UNIQUE_CAMPING_CARD_RFID_NUMBER ON CAMPING_CARD (CARD_RFID, CARD_NUMBER) WHERE DELETED = FALSE;
CREATE INDEX IDX_CAMPING_CARD_RFID ON CAMPING_CARD (CARD_RFID);
CREATE INDEX IDX_CAMPING_CARD_NUMBER ON CAMPING_CARD (CARD_NUMBER);
CREATE INDEX IDX_CAMPING_CARD_GUEST ON CAMPING_CARD (GUEST_ID);
