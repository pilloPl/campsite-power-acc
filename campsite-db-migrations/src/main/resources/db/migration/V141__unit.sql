-- Unit: what the guest stays in on the pitch (camper, caravan, tent). The plate of a camper or caravan is copied to
-- the supply sessions of its stays; the length decides which pitches fit.

CREATE SEQUENCE UNIT_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE UNIT
(
    ID          BIGINT        NOT NULL DEFAULT nextval('UNIT_ID_SEQ'),
    GUEST_ID    BIGINT        NOT NULL,
    UNIT_TYPE   VARCHAR(16)   NOT NULL,
    PLATE       VARCHAR(32),
    LENGTH_M    NUMERIC(4, 1),
    DESCRIPTION VARCHAR(255),
    CREATE_DATE TIMESTAMP     NOT NULL,
    DELETED     BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_UNIT PRIMARY KEY (ID),
    CONSTRAINT FK_UNIT_GUEST FOREIGN KEY (GUEST_ID) REFERENCES GUEST (ID),
    CONSTRAINT CHECK_UNIT_TYPE CHECK (UNIT_TYPE IN ('CAMPER', 'CARAVAN', 'TENT')),
    CONSTRAINT CHECK_UNIT_LENGTH CHECK (LENGTH_M IS NULL OR LENGTH_M > 0)
);

CREATE INDEX IDX_UNIT_GUEST ON UNIT (GUEST_ID);
CREATE INDEX IDX_UNIT_PLATE ON UNIT (PLATE);
