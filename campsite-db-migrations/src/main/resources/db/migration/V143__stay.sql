-- Stay: a guest on a pitch of a campsite from arrival to departure day (both inclusive). The camping card handed out
-- at check-in is valid exactly for the stay; check-out ends the card's validity and, after a delay, closes the supply
-- sessions the pedestals left open (SUPPLY_SESSION.STAY_ID, StopReason CHECKOUT).

CREATE SEQUENCE STAY_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE STAY
(
    ID             BIGINT       NOT NULL DEFAULT nextval('STAY_ID_SEQ'),
    GUEST_ID       BIGINT       NOT NULL,
    SITE_GROUP_ID  BIGINT       NOT NULL,
    PITCH_NO       VARCHAR(16),
    CARD_ID        BIGINT,
    UNIT_ID        BIGINT,
    ARRIVAL_DATE   DATE         NOT NULL,
    DEPARTURE_DATE DATE         NOT NULL,
    ADULTS         INTEGER      NOT NULL DEFAULT 1,
    CHILDREN       INTEGER      NOT NULL DEFAULT 0,
    CHECK_IN_DATE  TIMESTAMP    NOT NULL,
    CHECKED_IN_BY  VARCHAR(100),
    CHECK_OUT_DATE TIMESTAMP,
    CHECKED_OUT_BY VARCHAR(100),
    REMARKS        VARCHAR(1000),
    DELETED        BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_STAY PRIMARY KEY (ID),
    CONSTRAINT FK_STAY_GUEST FOREIGN KEY (GUEST_ID) REFERENCES GUEST (ID),
    CONSTRAINT FK_STAY_SITE_GROUP FOREIGN KEY (SITE_GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT FK_STAY_CARD FOREIGN KEY (CARD_ID) REFERENCES CAMPING_CARD (ID),
    CONSTRAINT FK_STAY_UNIT FOREIGN KEY (UNIT_ID) REFERENCES UNIT (ID),
    CONSTRAINT CHECK_STAY_DATES CHECK (ARRIVAL_DATE <= DEPARTURE_DATE),
    CONSTRAINT CHECK_STAY_PERSONS CHECK (ADULTS >= 1 AND CHILDREN >= 0),
    CONSTRAINT CHECK_STAY_CHECK_OUT CHECK (CHECK_OUT_DATE IS NULL OR CHECK_OUT_DATE >= CHECK_IN_DATE)
);

CREATE INDEX IDX_STAY_GUEST ON STAY (GUEST_ID);
CREATE INDEX IDX_STAY_CARD ON STAY (CARD_ID, ARRIVAL_DATE, DEPARTURE_DATE);
CREATE INDEX IDX_STAY_SITE_PITCH ON STAY (SITE_GROUP_ID, PITCH_NO);
CREATE INDEX IDX_STAY_CHECKED_OUT ON STAY (CHECK_OUT_DATE) WHERE CHECK_OUT_DATE IS NOT NULL;

-- the supply sessions of a stay; existed without the reference until the stays came
ALTER TABLE SUPPLY_SESSION
    ADD CONSTRAINT FK_SUPPLY_SESSION_STAY FOREIGN KEY (STAY_ID) REFERENCES STAY (ID);
