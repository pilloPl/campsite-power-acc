-- Audit trail of technical and functional actions (mails sent, imports, commissioning, exports ...).
-- Rows expire by category and status (AuditSuccessEventsExpiryPeriodInDays / AuditErrorEventsExpiryPeriodInDays).

CREATE SEQUENCE AUDIT_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE AUDIT
(
    ID              BIGINT        NOT NULL DEFAULT nextval('AUDIT_ID_SEQ'),
    DATE_CREATED    TIMESTAMP     NOT NULL,
    CATEGORY        VARCHAR(10)   NOT NULL,
    USERID          VARCHAR(100),
    ACTION_DATE     TIMESTAMP,
    ACTION_TYPE     VARCHAR(50),
    ACTION_NAME     VARCHAR(100),
    ACTION_GROUP_ID VARCHAR(50),
    STATUS          VARCHAR(15),
    ERROR_REASON    VARCHAR(2000),
    MANAGED_SERVER  VARCHAR(50),
    INFO_FIELD_1    VARCHAR(200),
    INFO_FIELD_2    VARCHAR(200),
    MESSAGE         VARCHAR(2000),
    AUDIT_DATA      VARCHAR(2000),
    CONSTRAINT PK_AUDIT PRIMARY KEY (ID),
    CONSTRAINT CHECK_AUDIT_CATEGORY CHECK (CATEGORY IN ('TECHNICAL', 'FUNCTIONAL'))
);

CREATE INDEX IDX_AUDIT_ACTION_DATE ON AUDIT (ACTION_DATE);
CREATE INDEX IDX_AUDIT_ACTION_TYPE ON AUDIT (ACTION_TYPE);
