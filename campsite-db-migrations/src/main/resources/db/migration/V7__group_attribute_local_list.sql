-- Local card list in the pedestal controller, inherited by the SITE subtree (nearest wins).

CREATE TABLE GRP_ATTR_LOCAL_LIST
(
    ID                  BIGINT  NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID            BIGINT  NOT NULL,
    LOCAL_LIST_ALLOWED  BOOLEAN NOT NULL,
    INCLUDE_CARDS       BOOLEAN NOT NULL,
    INCLUDE_HOUSE_CARDS BOOLEAN NOT NULL,
    CONSTRAINT PK_GRP_ATTR_LOCAL_LIST PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_LOCAL_LIST_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_LOCAL_LIST UNIQUE (GROUP_ID)
);
