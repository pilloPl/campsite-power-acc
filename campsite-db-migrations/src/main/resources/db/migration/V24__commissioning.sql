-- Commissioning of pedestals on an affiliate campsite: opened by staff for the affiliate owner with the address and
-- the access mode, carried out by the installer with the token, closed (soft deleted) when the pedestals are mounted.

CREATE SEQUENCE COMMISSIONING_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE COMMISSIONING
(
    ID                BIGINT      NOT NULL DEFAULT nextval('COMMISSIONING_ID_SEQ'),
    AFFILIATE_OWNER_ID BIGINT     NOT NULL,
    LOCATION_ID       BIGINT      NOT NULL,
    COMMENTS          VARCHAR(1000),
    LISTED_IN_APP     BOOLEAN     NOT NULL DEFAULT FALSE,
    ACCESS_MODE       VARCHAR(32) NOT NULL,
    TOKEN             VARCHAR(64) NOT NULL,
    CREATE_DATE       TIMESTAMP   NOT NULL,
    DELETE_DATE       TIMESTAMP,
    DELETED           BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_COMMISSIONING PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_COMMISSIONING_TOKEN UNIQUE (TOKEN),
    CONSTRAINT FK_COMMISSIONING_OWNER FOREIGN KEY (AFFILIATE_OWNER_ID) REFERENCES USERINFO (ID),
    CONSTRAINT FK_COMMISSIONING_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES LOCATION (ID),
    CONSTRAINT CHECK_COMMISSIONING_ACCESS_MODE CHECK (ACCESS_MODE IN ('NETWORK_ACCESS', 'HOUSE_CARDS_ONLY'))
);
