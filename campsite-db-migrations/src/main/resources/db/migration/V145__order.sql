-- Orders of seasonal contracts, cards and house card sets. The order keeps its own flat copy of the guest's details
-- as entered; a new guest is only known to the ERP after the partner and account numbers came back
-- (STATUS AWAITING_ERP_ACCOUNT, EXPORTED marks the orders handed to the ERP). ORDER_NUMBER comes from a sequence.

CREATE SEQUENCE ORDER_HEADER_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE SEQUENCE ORDER_NUMBER_SEQ START WITH 100001 INCREMENT BY 1;

CREATE TABLE ORDER_HEADER
(
    ID                   BIGINT        NOT NULL DEFAULT nextval('ORDER_HEADER_ID_SEQ'),
    ORDER_NUMBER         VARCHAR(32)   NOT NULL,
    GROUP_ID             BIGINT        NOT NULL,
    GUEST_ID             BIGINT,
    BILLING_ACCOUNT_ID   BIGINT,
    STATUS               VARCHAR(32)   NOT NULL DEFAULT 'NEW',
    GUEST_TYPE           VARCHAR(16)   NOT NULL,
    SALUTATION           VARCHAR(16),
    NAME                 VARCHAR(255)  NOT NULL,
    FIRST_NAME           VARCHAR(255),
    INITIALS             VARCHAR(32),
    ORGANISATION_NAME    VARCHAR(200),
    VAT_NUMBER           VARCHAR(32),
    STREET               VARCHAR(100),
    HOUSE_NO             VARCHAR(16),
    HOUSE_NO_ADD         VARCHAR(16),
    ZIP_CODE             VARCHAR(16),
    CITY                 VARCHAR(100),
    COUNTRY_ISO          VARCHAR(2),
    LANGUAGE             VARCHAR(8),
    EMAIL                VARCHAR(255),
    PHONE                VARCHAR(32),
    MOBILE               VARCHAR(32),
    BANK_ACCOUNT_NAME    VARCHAR(200),
    IBAN                 VARCHAR(34),
    PAYMENT_METHOD       VARCHAR(32),
    CAR_PLATE            VARCHAR(32),
    TRAILER_PLATE        VARCHAR(32),
    HAS_DELIVERY_CONTACT BOOLEAN       NOT NULL DEFAULT FALSE,
    DELIVERY_NAME        VARCHAR(255),
    DELIVERY_STREET      VARCHAR(100),
    DELIVERY_HOUSE_NO    VARCHAR(16),
    DELIVERY_ZIP_CODE    VARCHAR(16),
    DELIVERY_CITY        VARCHAR(100),
    DELIVERY_COUNTRY_ISO VARCHAR(2),
    ERP_PARTNER_NO       VARCHAR(32),
    ERP_ACCOUNT_NO       VARCHAR(40),
    EXPORTED             BOOLEAN       NOT NULL DEFAULT FALSE,
    EXPORT_DATE          TIMESTAMP,
    REMARKS              VARCHAR(2000),
    CREATE_DATE          TIMESTAMP     NOT NULL,
    CREATED_BY           VARCHAR(100),
    MOD_DATE             TIMESTAMP,
    ACTIVATION_DATE      TIMESTAMP,
    CONSTRAINT PK_ORDER_HEADER PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_ORDER_HEADER_NUMBER UNIQUE (ORDER_NUMBER),
    CONSTRAINT FK_ORDER_HEADER_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT FK_ORDER_HEADER_GUEST FOREIGN KEY (GUEST_ID) REFERENCES GUEST (ID),
    CONSTRAINT FK_ORDER_HEADER_BILLING_ACCOUNT FOREIGN KEY (BILLING_ACCOUNT_ID) REFERENCES BILLING_ACCOUNT (ID),
    CONSTRAINT CHECK_ORDER_HEADER_STATUS CHECK (STATUS IN ('NEW', 'AWAITING_ERP_ACCOUNT', 'ACTIVE', 'CANCELLED')),
    CONSTRAINT CHECK_ORDER_HEADER_GUEST_TYPE CHECK (GUEST_TYPE IN ('TRANSIT', 'SEASONAL')),
    CONSTRAINT CHECK_ORDER_HEADER_ACTIVE CHECK (STATUS <> 'ACTIVE'
        OR (GUEST_ID IS NOT NULL AND ERP_PARTNER_NO IS NOT NULL AND ERP_ACCOUNT_NO IS NOT NULL))
);

CREATE INDEX IDX_ORDER_HEADER_GUEST ON ORDER_HEADER (GUEST_ID);
CREATE INDEX IDX_ORDER_HEADER_STATUS ON ORDER_HEADER (STATUS, EXPORTED);
CREATE INDEX IDX_ORDER_HEADER_ERP ON ORDER_HEADER (ERP_PARTNER_NO, ERP_ACCOUNT_NO);

CREATE SEQUENCE ORDER_ITEM_ID_SEQ START WITH 1000 INCREMENT BY 1;

-- one product of the order, with the price and package as ordered (the catalogue may change later)
CREATE TABLE ORDER_ITEM
(
    ID                    BIGINT         NOT NULL DEFAULT nextval('ORDER_ITEM_ID_SEQ'),
    ORDER_ID              BIGINT         NOT NULL,
    POS                   INTEGER        NOT NULL,
    PRODUCT_DEFINITION_ID BIGINT         NOT NULL,
    TITLE                 VARCHAR(128)   NOT NULL,
    QUANTITY              INTEGER        NOT NULL DEFAULT 1,
    FIXED_PRICE           NUMERIC(19, 2),
    FIXED_PRICE_PERIOD    VARCHAR(16),
    PACKAGE_KWH           NUMERIC(19, 4),
    SITE_GROUP_ID         BIGINT,
    PITCH_NO              VARCHAR(16),
    START_DATE            DATE,
    END_DATE              DATE,
    CARD_ID               BIGINT,
    REQUESTED_CARD_NUMBER VARCHAR(64),
    CONSTRAINT PK_ORDER_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_ORDER_ITEM_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDER_HEADER (ID),
    CONSTRAINT FK_ORDER_ITEM_PRODUCT FOREIGN KEY (PRODUCT_DEFINITION_ID) REFERENCES PRODUCT_DEFINITION (ID),
    CONSTRAINT FK_ORDER_ITEM_SITE_GROUP FOREIGN KEY (SITE_GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT FK_ORDER_ITEM_CARD FOREIGN KEY (CARD_ID) REFERENCES CAMPING_CARD (ID),
    CONSTRAINT UNIQUE_ORDER_ITEM_POS UNIQUE (ORDER_ID, POS),
    CONSTRAINT CHECK_ORDER_ITEM_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CHECK_ORDER_ITEM_DATES CHECK (START_DATE IS NULL OR END_DATE IS NULL OR START_DATE <= END_DATE)
);

CREATE INDEX IDX_ORDER_ITEM_ORDER ON ORDER_ITEM (ORDER_ID);
