-- Group attributes: one table per attribute, all ids from one sequence.
-- Resolution everywhere: the attribute of the nearest ancestor-or-self wins.

CREATE SEQUENCE GROUP_ATTRIBUTE_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE GRP_ATTR_SITE_TENANT
(
    ID       BIGINT       NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID BIGINT       NOT NULL,
    NAME     VARCHAR(256) NOT NULL,
    CONSTRAINT PK_GRP_ATTR_SITE_TENANT PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_SITE_TENANT_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_SITE_TENANT UNIQUE (GROUP_ID)
);

CREATE TABLE GRP_ATTR_ISSUER_TENANT
(
    ID       BIGINT       NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID BIGINT       NOT NULL,
    NAME     VARCHAR(256) NOT NULL,
    CONSTRAINT PK_GRP_ATTR_ISSUER_TENANT PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_ISSUER_TENANT_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_ISSUER_TENANT UNIQUE (GROUP_ID)
);
