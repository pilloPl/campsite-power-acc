-- Pedestal types: manufacturer and model of the pedestal controller, its link generation and capabilities.

CREATE SEQUENCE PEDESTAL_TYPE_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE PEDESTAL_TYPE
(
    ID                       BIGINT       NOT NULL DEFAULT nextval('PEDESTAL_TYPE_ID_SEQ'),
    NAME                     VARCHAR(128) NOT NULL,
    MANUFACTURER             VARCHAR(128) NOT NULL,
    LINK_VERSION             VARCHAR(8)   NOT NULL,
    REMOTE_BREAKER_RESET     BOOLEAN      NOT NULL DEFAULT FALSE,
    LOCAL_CARD_LIST          BOOLEAN      NOT NULL DEFAULT FALSE,
    LOCAL_CARD_LIST_CAPACITY INTEGER,
    MAX_SOCKETS              INTEGER      NOT NULL DEFAULT 6,
    DESCRIPTION              VARCHAR(50),
    CODE                     BIGINT,
    DELETED                  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_PEDESTAL_TYPE PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_PEDESTAL_TYPE UNIQUE (MANUFACTURER, NAME),
    CONSTRAINT CHECK_PEDESTAL_TYPE_LINK CHECK (LINK_VERSION IN ('V1', 'V2', 'V3')),
    CONSTRAINT CHECK_PEDESTAL_TYPE_SOCKETS CHECK (MAX_SOCKETS BETWEEN 1 AND 6)
);
