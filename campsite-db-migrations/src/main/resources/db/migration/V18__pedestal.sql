-- Pedestal: the hook-up post on a campsite with 1-6 metered sockets and a modem. Hangs in a SITE group
-- (campsite or section, or the supplier stock before commissioning). Flags decide billing and visibility.

CREATE SEQUENCE PEDESTAL_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE PEDESTAL
(
    ID                          BIGINT       NOT NULL DEFAULT nextval('PEDESTAL_ID_SEQ'),
    CODE                        VARCHAR(128) NOT NULL,
    PEDESTAL_TYPE_ID            BIGINT       NOT NULL,
    LOCATION_ID                 BIGINT       NOT NULL,
    GROUP_ID                    BIGINT,
    REFERENCE_ID                VARCHAR(50),
    SERIAL_NUMBER               VARCHAR(64),
    FIRMWARE_VERSION            VARCHAR(64),
    MODEM_ICCID                 VARCHAR(32),
    YEAR_OF_INSTALLATION        DATE,
    DESCRIPTION                 VARCHAR(128),
    PRICE_INFORMATION           VARCHAR(50),
    BILLABLE                    BOOLEAN      NOT NULL DEFAULT FALSE,
    SETTLED_BY_CAMPSITE         BOOLEAN      NOT NULL DEFAULT FALSE,
    LISTED_IN_APP               BOOLEAN      NOT NULL DEFAULT TRUE,
    AUTOMATED_WHITELIST_UPDATES BOOLEAN      NOT NULL DEFAULT FALSE,
    MANAGED_EXTERNALLY          BOOLEAN      NOT NULL DEFAULT FALSE,
    REMOTE_CONTROL              BOOLEAN      NOT NULL DEFAULT TRUE,
    DELETED                     BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_PEDESTAL PRIMARY KEY (ID),
    CONSTRAINT UNIQUE_PEDESTAL_CODE UNIQUE (CODE),
    CONSTRAINT FK_PEDESTAL_TYPE FOREIGN KEY (PEDESTAL_TYPE_ID) REFERENCES PEDESTAL_TYPE (ID),
    CONSTRAINT FK_PEDESTAL_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES LOCATION (ID),
    CONSTRAINT FK_PEDESTAL_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID)
);

CREATE INDEX IDX_PEDESTAL_GROUP ON PEDESTAL (GROUP_ID);
CREATE INDEX IDX_PEDESTAL_LOCATION ON PEDESTAL (LOCATION_ID);
CREATE INDEX IDX_PEDESTAL_REFERENCE ON PEDESTAL (REFERENCE_ID);
