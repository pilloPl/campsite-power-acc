-- Default tariff of a SITE subtree (campsite, section): replaces the "market to tariff" fallback below the market
-- level. Nearest ancestor-or-self wins, like every group attribute.

CREATE TABLE GRP_ATTR_DEFAULT_TARIFF
(
    ID        BIGINT NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID  BIGINT NOT NULL,
    TARIFF_ID BIGINT NOT NULL,
    CONSTRAINT PK_GRP_ATTR_DEFAULT_TARIFF PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_DEFAULT_TARIFF_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT FK_GRP_ATTR_DEFAULT_TARIFF_TARIFF FOREIGN KEY (TARIFF_ID) REFERENCES TARIFF (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_DEFAULT_TARIFF UNIQUE (GROUP_ID)
);
