-- Seasonal contract: a fixed pitch of a campsite for the season, a fixed fee (per month or for the season) and a kWh
-- package included (sum of the PACKAGE_ITEM rows); the kWh above the package are priced by the contract's tariff,
-- which overrides every tariff of the pedestal while the contract is active. Billed to one billing account.

CREATE SEQUENCE SEASONAL_CONTRACT_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE SEASONAL_CONTRACT
(
    ID                 BIGINT         NOT NULL DEFAULT nextval('SEASONAL_CONTRACT_ID_SEQ'),
    BILLING_ACCOUNT_ID BIGINT         NOT NULL,
    ORDER_ITEM_ID      BIGINT,
    TARIFF_ID          BIGINT         NOT NULL,
    STATUS             VARCHAR(32)    NOT NULL DEFAULT 'ACTIVE',
    SITE_GROUP_ID      BIGINT,
    PITCH_NO           VARCHAR(16),
    START_DATE         DATE           NOT NULL,
    END_DATE           DATE,
    REQUESTED_END_DATE DATE,
    FIXED_FEE          NUMERIC(19, 2) NOT NULL DEFAULT 0,
    FEE_PERIOD         VARCHAR(16)    NOT NULL DEFAULT 'SEASONAL',
    CREATE_DATE        TIMESTAMP      NOT NULL,
    MOD_DATE           TIMESTAMP,
    CONSTRAINT PK_SEASONAL_CONTRACT PRIMARY KEY (ID),
    CONSTRAINT FK_SEASONAL_CONTRACT_ACCOUNT FOREIGN KEY (BILLING_ACCOUNT_ID) REFERENCES BILLING_ACCOUNT (ID),
    CONSTRAINT FK_SEASONAL_CONTRACT_ORDER_ITEM FOREIGN KEY (ORDER_ITEM_ID) REFERENCES ORDER_ITEM (ID),
    CONSTRAINT FK_SEASONAL_CONTRACT_TARIFF FOREIGN KEY (TARIFF_ID) REFERENCES TARIFF (ID),
    CONSTRAINT FK_SEASONAL_CONTRACT_SITE_GROUP FOREIGN KEY (SITE_GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT CHECK_SEASONAL_CONTRACT_STATUS CHECK (STATUS IN ('ACTIVE', 'ENDED', 'TERMINATION_REQUESTED')),
    CONSTRAINT CHECK_SEASONAL_CONTRACT_PERIOD CHECK (FEE_PERIOD IN ('MONTHLY', 'SEASONAL')),
    CONSTRAINT CHECK_SEASONAL_CONTRACT_DATES CHECK (END_DATE IS NULL OR START_DATE <= END_DATE),
    CONSTRAINT CHECK_SEASONAL_CONTRACT_FEE CHECK (FIXED_FEE >= 0),
    CONSTRAINT CHECK_SEASONAL_CONTRACT_PITCH CHECK (PITCH_NO IS NULL OR SITE_GROUP_ID IS NOT NULL)
);

CREATE INDEX IDX_SEASONAL_CONTRACT_ACCOUNT ON SEASONAL_CONTRACT (BILLING_ACCOUNT_ID, START_DATE);
CREATE INDEX IDX_SEASONAL_CONTRACT_PITCH ON SEASONAL_CONTRACT (SITE_GROUP_ID, PITCH_NO);

CREATE SEQUENCE PACKAGE_ITEM_ID_SEQ START WITH 1000 INCREMENT BY 1;

-- the products of a contract: each brings its kWh package
CREATE TABLE PACKAGE_ITEM
(
    ID                    BIGINT         NOT NULL DEFAULT nextval('PACKAGE_ITEM_ID_SEQ'),
    CONTRACT_ID           BIGINT         NOT NULL,
    ORDER_ITEM_ID         BIGINT,
    PRODUCT_DEFINITION_ID BIGINT         NOT NULL,
    PACKAGE_KWH           NUMERIC(19, 4) NOT NULL DEFAULT 0,
    CONSTRAINT PK_PACKAGE_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_PACKAGE_ITEM_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES SEASONAL_CONTRACT (ID),
    CONSTRAINT FK_PACKAGE_ITEM_ORDER_ITEM FOREIGN KEY (ORDER_ITEM_ID) REFERENCES ORDER_ITEM (ID),
    CONSTRAINT FK_PACKAGE_ITEM_PRODUCT FOREIGN KEY (PRODUCT_DEFINITION_ID) REFERENCES PRODUCT_DEFINITION (ID),
    CONSTRAINT UNIQUE_PACKAGE_ITEM_ORDER_ITEM UNIQUE (CONTRACT_ID, ORDER_ITEM_ID),
    CONSTRAINT CHECK_PACKAGE_ITEM_KWH CHECK (PACKAGE_KWH >= 0)
);

CREATE INDEX IDX_PACKAGE_ITEM_CONTRACT ON PACKAGE_ITEM (CONTRACT_ID);
