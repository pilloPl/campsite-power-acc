-- Pedestal stock of a manufacturer ("SUPPLIER <manufacturer>"), inherited by the SITE subtree (nearest wins).

CREATE TABLE GRP_ATTR_SUPPLIER
(
    ID       BIGINT       NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID BIGINT       NOT NULL,
    NAME     VARCHAR(256) NOT NULL,
    ACTIVE   BOOLEAN      NOT NULL,
    CONSTRAINT PK_GRP_ATTR_SUPPLIER PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_SUPPLIER_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_SUPPLIER UNIQUE (GROUP_ID)
);
