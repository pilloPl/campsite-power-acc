-- Incidents of the supply: the pedestal stopped a supply the pedestal backend cannot book (no transaction id, no
-- session, session already closed). The pedestal always gets ACCEPTED for its stop; the incident is kept here for
-- the service team and the reports.

CREATE SEQUENCE SUPPLY_INCIDENT_LOG_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE SUPPLY_INCIDENT_LOG
(
    ID                BIGINT         NOT NULL DEFAULT nextval('SUPPLY_INCIDENT_LOG_ID_SEQ'),
    INCIDENT_TYPE     VARCHAR(32)    NOT NULL,
    PEDESTAL_CODE     VARCHAR(64),
    TRANSACTION_ID    INTEGER,
    CARD_RFID         VARCHAR(64),
    SUPPLY_SESSION_ID BIGINT,
    METER_KWH         NUMERIC(19, 4),
    REMOTE_DATE       TIMESTAMP,
    MESSAGE           VARCHAR(1000)  NOT NULL,
    CREATE_DATE       TIMESTAMP      NOT NULL,
    CONSTRAINT PK_SUPPLY_INCIDENT_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_SUPPLY_INCIDENT_LOG_SESSION FOREIGN KEY (SUPPLY_SESSION_ID) REFERENCES SUPPLY_SESSION (ID),
    CONSTRAINT CHECK_SUPPLY_INCIDENT_LOG_TYPE CHECK (INCIDENT_TYPE IN ('NO_TRANSACTION_ID', 'NO_SESSION',
        'SESSION_ALREADY_CLOSED'))
);

CREATE INDEX IDX_SUPPLY_INCIDENT_LOG_CREATED ON SUPPLY_INCIDENT_LOG (CREATE_DATE);
CREATE INDEX IDX_SUPPLY_INCIDENT_LOG_PEDESTAL ON SUPPLY_INCIDENT_LOG (PEDESTAL_CODE);
