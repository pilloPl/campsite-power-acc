-- QR payment at the socket: a transit guest without a card scans the code on the socket and pays in the payment
-- app. The app's order is a process whose states are stored as a chain of rows: every transition inserts a new
-- row and links the old one to it (NEXT_PROCESS_ID). The current row of a process is the one without successor.
-- PROCESS_ID is the id of the first row and stays the same along the chain; the pedestal gets it as the auth tag
-- of the remote supply start ("QR" + PROCESS_ID) and the supply session keeps it in SUPPLY_SESSION.QRPAY_PROCESS_ID.
-- START_TIME / STOP_TIME are the period of the row's state. The app's order reference is unique per process
-- (checked on the first row). Finished chains move to QRPAY_PROCESS_ARCHIVE.

CREATE SEQUENCE QRPAY_PROCESS_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE QRPAY_PROCESS
(
    ID                  BIGINT         NOT NULL DEFAULT nextval('QRPAY_PROCESS_ID_SEQ'),
    PROCESS_ID          BIGINT         NOT NULL,
    ORDER_REFERENCE     VARCHAR(64)    NOT NULL,
    STATE               VARCHAR(40)    NOT NULL,
    SOCKET_ID           BIGINT         NOT NULL,
    CLIENT_USERNAME     VARCHAR(255)   NOT NULL,
    APP_USER_ID         VARCHAR(255)   NOT NULL,
    REQUEST_DATE        TIMESTAMP      NOT NULL,
    START_TIME          TIMESTAMP      NOT NULL,
    STOP_TIME           TIMESTAMP,
    PRICE_INFORMATION   VARCHAR(255),
    SUPPLY_SESSION_ID   BIGINT,
    TRANSACTION_ID      INTEGER,
    KWH                 NUMERIC(19, 4),
    DURATION_SECONDS    BIGINT,
    COST                NUMERIC(19, 2),
    CURRENCY            VARCHAR(3),
    ERROR_CODE          VARCHAR(40),
    ERROR_MESSAGE       VARCHAR(1024),
    PREVIOUS_PROCESS_ID BIGINT,
    NEXT_PROCESS_ID     BIGINT,
    CONSTRAINT PK_QRPAY_PROCESS PRIMARY KEY (ID),
    CONSTRAINT FK_QRPAY_PROCESS_SOCKET FOREIGN KEY (SOCKET_ID) REFERENCES SOCKET (ID),
    CONSTRAINT FK_QRPAY_PROCESS_PREVIOUS FOREIGN KEY (PREVIOUS_PROCESS_ID) REFERENCES QRPAY_PROCESS (ID),
    CONSTRAINT FK_QRPAY_PROCESS_NEXT FOREIGN KEY (NEXT_PROCESS_ID) REFERENCES QRPAY_PROCESS (ID),
    CONSTRAINT UNIQUE_QRPAY_PROCESS_NEXT UNIQUE (NEXT_PROCESS_ID),
    CONSTRAINT CHECK_QRPAY_PROCESS_STATE CHECK (STATE IN ('START_REQUESTED', 'SOCKET_START_WAITING',
        'SOCKET_START_RECEIVED', 'START_CONFIRMED', 'STOP_REQUESTED', 'SOCKET_STOP_WAITING', 'SOCKET_STOP_RECEIVED',
        'CALCULATION_REQUESTED', 'CALCULATION_DONE', 'CLOSED', 'ERROR')),
    CONSTRAINT CHECK_QRPAY_PROCESS_FIRST_ROW CHECK ((PREVIOUS_PROCESS_ID IS NULL) = (ID = PROCESS_ID))
);

-- one process per order reference of the app (the first row carries it for the whole chain)
CREATE UNIQUE INDEX UNIQUE_QRPAY_PROCESS_ORDER_REFERENCE ON QRPAY_PROCESS (ORDER_REFERENCE)
    WHERE PREVIOUS_PROCESS_ID IS NULL;
CREATE INDEX IDX_QRPAY_PROCESS_CURRENT ON QRPAY_PROCESS (PROCESS_ID) WHERE NEXT_PROCESS_ID IS NULL;
CREATE INDEX IDX_QRPAY_PROCESS_CURRENT_ORDER ON QRPAY_PROCESS (ORDER_REFERENCE) WHERE NEXT_PROCESS_ID IS NULL;
CREATE INDEX IDX_QRPAY_PROCESS_CURRENT_SOCKET ON QRPAY_PROCESS (SOCKET_ID) WHERE NEXT_PROCESS_ID IS NULL;
CREATE INDEX IDX_QRPAY_PROCESS_PREVIOUS ON QRPAY_PROCESS (PREVIOUS_PROCESS_ID);
