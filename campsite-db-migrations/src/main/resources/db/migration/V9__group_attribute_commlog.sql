-- Pedestal link communication log switch, inherited by the SITE subtree (nearest wins).

CREATE TABLE GRP_ATTR_COMMLOG
(
    ID       BIGINT       NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID BIGINT       NOT NULL,
    NAME     VARCHAR(256) NOT NULL,
    ACTIVE   BOOLEAN      NOT NULL,
    CONSTRAINT PK_GRP_ATTR_COMMLOG PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_COMMLOG_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_COMMLOG UNIQUE (GROUP_ID)
);
