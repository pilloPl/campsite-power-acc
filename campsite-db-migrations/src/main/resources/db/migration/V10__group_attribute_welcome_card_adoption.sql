-- Adoption of welcome cards by affiliate campsites, inherited by the SITE subtree (nearest wins).

CREATE TABLE GRP_ATTR_WELCOME_CARD_ADOPTION
(
    ID       BIGINT  NOT NULL DEFAULT nextval('GROUP_ATTRIBUTE_ID_SEQ'),
    GROUP_ID BIGINT  NOT NULL,
    ALLOWED  BOOLEAN NOT NULL,
    CONSTRAINT PK_GRP_ATTR_WELCOME_CARD_ADOPTION PRIMARY KEY (ID),
    CONSTRAINT FK_GRP_ATTR_WELCOME_CARD_ADOPTION_GROUP FOREIGN KEY (GROUP_ID) REFERENCES TBL_GROUP (ID),
    CONSTRAINT UNIQUE_GRP_ATTR_WELCOME_CARD_ADOPTION UNIQUE (GROUP_ID)
);
