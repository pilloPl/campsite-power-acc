-- Link state of a pedestal: when the last message arrived and whether the heartbeat timed out.
-- One row per pedestal, created with the first message.

CREATE SEQUENCE PEDESTAL_STATE_ID_SEQ START WITH 1000 INCREMENT BY 1;

CREATE TABLE PEDESTAL_STATE
(
    ID                   BIGINT    NOT NULL DEFAULT nextval('PEDESTAL_STATE_ID_SEQ'),
    PEDESTAL_ID          BIGINT    NOT NULL,
    APPROX_LAST_INCOMING TIMESTAMP NOT NULL,
    LAST_TIMEOUT         TIMESTAMP,
    TIMEOUT              BOOLEAN   NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_PEDESTAL_STATE PRIMARY KEY (ID),
    CONSTRAINT FK_PEDESTAL_STATE_PEDESTAL FOREIGN KEY (PEDESTAL_ID) REFERENCES PEDESTAL (ID),
    CONSTRAINT UNIQUE_PEDESTAL_STATE_PEDESTAL UNIQUE (PEDESTAL_ID)
);
