-- Demo data (profile demo): removes the rows of an earlier demo seed. Demo rows have ids from 900000000 on; rows the
-- application created later on demo pedestals, sockets, cards, guests or groups (sessions, records, logs, QR
-- payments, stays) go with them. Children before parents.

DELETE FROM AUDIT WHERE ID >= 900000000;
-- acknowledgements of dashboard alerts refer to objects by id in their key; a reseed shows all alerts again
DELETE FROM CONSOLE_ALERT_ACK;
DELETE FROM EVENT_RETRY WHERE ID >= 900000000;

DELETE FROM ISSUER_SYNC_STATUS WHERE ID >= 900000000 OR ISSUER_PARTNER_ID >= 900000000;
DELETE FROM GRP_ATTR_WHITELIST_FILTER WHERE ID >= 900000000 OR GROUP_ID >= 900000000 OR ISSUER_PARTNER_ID >= 900000000;
-- filters set in the console on the groups of the migrations (ids of the sequence, from 1000 on) go as well
DELETE FROM GRP_ATTR_WHITELIST_FILTER WHERE ID >= 1000;

DROP TABLE IF EXISTS pg_temp.DEMO_OLD_SESSION;
CREATE TEMPORARY TABLE DEMO_OLD_SESSION AS
SELECT ID
  FROM SUPPLY_SESSION
 WHERE ID >= 900000000 OR SOCKET_ID >= 900000000 OR CARD_ID >= 900000000 OR HOUSECARD_ID >= 900000000
    OR STAY_ID >= 900000000;

DELETE FROM CONSUMPTION_RECORD
 WHERE ID >= 900000000 OR SOCKET_ID >= 900000000 OR PEDESTAL_ID >= 900000000 OR GUEST_ID >= 900000000
    OR CARD_ID >= 900000000 OR HOUSECARD_ID >= 900000000 OR SITE_GROUP_ID >= 900000000
    OR SUPPLY_SESSION_ID IN (SELECT ID FROM DEMO_OLD_SESSION);
DELETE FROM ERP_BILLING_LINE WHERE ID >= 900000000 OR BILLING_ACCOUNT_ID >= 900000000;
DELETE FROM SUPPLY_INCIDENT_LOG WHERE ID >= 900000000 OR SUPPLY_SESSION_ID IN (SELECT ID FROM DEMO_OLD_SESSION);
DELETE FROM SUPPLY_SESSION WHERE ID IN (SELECT ID FROM DEMO_OLD_SESSION);
DROP TABLE pg_temp.DEMO_OLD_SESSION;

